const fn op(
    opcode: &'static str,
    aliases: &'static [&'static str],
    args: &'static [&'static str],
    returns: &'static str,
    summary: &'static str,
) -> OperationSpec {
    OperationSpec { opcode, aliases, args, returns, summary, source: OperationSource::BuiltIn }
}

static EXACT_LOOKUP: OnceLock<HashMap<&'static str, usize>> = OnceLock::new();
static LOOKUP: OnceLock<HashMap<String, usize>> = OnceLock::new();
static FAMILY_INDEX: OnceLock<HashMap<String, Vec<usize>>> = OnceLock::new();

fn exact_lookup() -> &'static HashMap<&'static str, usize> {
    EXACT_LOOKUP.get_or_init(|| {
        let mut map = HashMap::with_capacity(OPERATIONS.len() * 2);
        for (index, spec) in OPERATIONS.iter().enumerate() {
            map.entry(spec.opcode).or_insert(index);
            for alias in spec.aliases {
                map.entry(*alias).or_insert(index);
            }
        }
        map
    })
}

fn lookup() -> &'static HashMap<String, usize> {
    LOOKUP.get_or_init(|| {
        let mut map = HashMap::with_capacity(OPERATIONS.len() * 2);
        for (index, spec) in OPERATIONS.iter().enumerate() {
            map.entry(spec.opcode.to_ascii_lowercase()).or_insert(index);
            for alias in spec.aliases {
                map.entry(alias.to_ascii_lowercase()).or_insert(index);
            }
        }
        map
    })
}

fn family_index() -> &'static HashMap<String, Vec<usize>> {
    FAMILY_INDEX.get_or_init(|| {
        let mut map: HashMap<String, Vec<usize>> = HashMap::new();
        for (index, spec) in OPERATIONS.iter().enumerate() {
            if let Some((family, _)) = spec.opcode.split_once('.') {
                map.entry(family.to_string()).or_default().push(index);
            }
        }
        map
    })
}

pub fn resolve(name: &str) -> Option<&'static OperationSpec> {
    let raw = name.trim();
    if let Some(index) = exact_lookup().get(raw) {
        return OPERATIONS.get(*index);
    }
    let needle = raw.to_ascii_lowercase();
    lookup().get(&needle).and_then(|index| OPERATIONS.get(*index))
}

pub fn search(query: &str, limit: usize) -> Vec<&'static OperationSpec> {
    let q = query.trim().to_ascii_lowercase();
    if q.is_empty() {
        return Vec::new();
    }

    let family_hint = q.split_once('.').map(|(f, _)| f).unwrap_or(q.as_str());
    let candidates: Vec<usize> = family_index()
        .get(family_hint)
        .cloned()
        .unwrap_or_else(|| (0..OPERATIONS.len()).collect());

    // Generic aliases can intentionally exist in more than one family (for example
    // `mean`, `sin`, or `power`). `resolve()` deterministically gives ownership to
    // the first registered operation. Search must use the same ownership rule so an
    // exact alias query cannot disagree with exact resolution merely because another
    // opcode sorts earlier alphabetically.
    let preferred_index = exact_lookup().get(query.trim()).copied().or_else(|| lookup().get(&q).copied());
    let mut scored: Vec<(u8, u8, &OperationSpec)> = candidates
        .into_iter()
        .filter_map(|index| {
            let spec = &OPERATIONS[index];
            let exact = spec.opcode.eq_ignore_ascii_case(&q)
                || spec.aliases.iter().any(|a| a.eq_ignore_ascii_case(&q));
            let prefix = spec.opcode.starts_with(&q) || spec.aliases.iter().any(|a| a.starts_with(&q));
            let contains = spec.opcode.contains(&q)
                || spec.summary.contains(&q)
                || spec.aliases.iter().any(|a| a.contains(&q));
            let owner_rank = if preferred_index == Some(index) { 0 } else { 1 };
            if exact {
                Some((0, owner_rank, spec))
            } else if prefix {
                Some((1, owner_rank, spec))
            } else if contains {
                Some((2, owner_rank, spec))
            } else {
                None
            }
        })
        .collect();
    scored.sort_by_key(|(score, owner_rank, spec)| (*score, *owner_rank, spec.opcode));
    scored
        .into_iter()
        .take(limit)
        .map(|(_, _, spec)| spec)
        .collect()
}

pub fn capability_code(opcode: &str) -> &'static str {
    if opcode.starts_with("int.") || opcode.starts_with("dec.") || opcode.starts_with("base.") || opcode.starts_with("disc.") { "ed" }
    else if opcode.starts_with("udo.") { "dc" }
    else if opcode == "expr.eval" || opcode.starts_with("num.") || opcode.starts_with("alg.") || opcode.starts_with("cplx.") || opcode.starts_with("phys.") || opcode.starts_with("eng.") || opcode.starts_with("reg.") || opcode.starts_with("test.") || opcode.starts_with("chem.") || opcode.starts_with("net.") || opcode.starts_with("color.") || opcode.starts_with("info.") || opcode.starts_with("astro.") || opcode.starts_with("time.") || opcode.starts_with("geod.") || opcode.starts_with("thermo.") || opcode.starts_with("mech.") || opcode.starts_with("fluid.") || opcode.starts_with("elec.") || opcode.starts_with("optics.") || opcode.starts_with("wave.") || opcode.starts_with("data.") { "d" }
    else if opcode.starts_with("stat.") || opcode.starts_with("vec.") || opcode.starts_with("mat.") || opcode.starts_with("signal.") || opcode.starts_with("prob.") { "dv" }
    else { "d" }
}

pub fn cost_code(opcode: &str) -> &'static str {
    if opcode == "mat.mul" { "n3" }
    else if opcode == "int.pow"
        || opcode.starts_with("mat.") || opcode.starts_with("num.")
        || opcode.starts_with("linalg.") || opcode.starts_with("optimize.") || opcode.starts_with("ode.")
        || matches!(opcode, "series.euler_transform" | "series.fourier_coefficients" | "series.chebyshev_coefficients")
        || opcode.starts_with("signal.fft") || opcode.starts_with("signal.dft") || opcode.starts_with("alg.prime")
        || matches!(opcode, "disc.bell" | "disc.stirling2" | "disc.surjections" | "info.levenshtein" | "curve.self_intersections" | "curve.is_simple_closed" | "curve.audit") { "h" }
    else if opcode.starts_with("stat.") || opcode.starts_with("signal.") || opcode.starts_with("prob.")
        || opcode.starts_with("base.") || opcode.starts_with("disc.") || opcode.starts_with("info.")
        || opcode.starts_with("data.") || opcode.starts_with("series.") || opcode.starts_with("special.") { "n" }
    else if opcode.starts_with("udo.") { "c" }
    else { "1" }
}
